#!/usr/bin/env python3
"""Port Omarchy's themes to omac. Reads an Omarchy checkout and writes
themes/omarchy/<id>/ with ready-to-copy files for every app omac themes:
Ghostty, btop, tmux, herdr (CLI + app), lazygit, fzf, starship and Neovim.

Usage: python3 -I themes/omarchy-themes.py [path/to/omarchy]
       (default: $OMARCHY_SRC, then research/device/omarchy-repo)
       A checkout of https://github.com/basecamp/omarchy works.

Outputs are committed, so installing omac never needs Omarchy or Python.
Re-run after pulling a newer Omarchy, then `omac theme <id>` to apply.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "omarchy")
HEADER = "Generated by themes/omarchy-themes.py from Omarchy's colors.toml. Re-run it, don't edit this file."
TEMPLATES = ("ghostty.conf.tpl", "btop.theme.tpl", "neovim.lua.tpl")

# Omarchy theme slugs that clash with omac's own names get a prefix.
RENAME = {"white": "omarchy-white"}


# ── colors.toml (mirrors omarchy-theme-color's fallback cascade) ──────────────
def parse_colors(path):
    colors = {}
    with open(path) as f:
        for line in f:
            if line.lstrip().startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            key = re.sub(r"[\"' ]", "", key)
            if not key:
                continue
            m = re.search(r"[\"']([^\"']*)[\"']", value)
            colors[key] = m.group(1) if m else value.split("#", 1)[0].strip()
    return colors


def mix(a, b, amount):
    a, b = a.lstrip("#"), b.lstrip("#")
    out = []
    for i in (0, 2, 4):
        x, y = int(a[i:i + 2], 16), int(b[i:i + 2], 16)
        out.append(int(x * (1 - amount) + y * amount + 0.5))
    return "#%02x%02x%02x" % tuple(out)


def resolve(c):
    def alias(key, fallback):
        if not c.get(key) and c.get(fallback):
            c[key] = c[fallback]

    for key, short in (("background", "bg"), ("dark_background", "dark_bg"), ("darker_background", "darker_bg"),
                       ("lighter_background", "lighter_bg"), ("foreground", "fg"), ("dark_foreground", "dark_fg"),
                       ("light_foreground", "light_fg"), ("bright_foreground", "bright_fg")):
        alias(key, short)
    alias("background", "color0")
    alias("foreground", "color7")
    for key, n in (("red", 1), ("green", 2), ("yellow", 3), ("blue", 4), ("magenta", 5), ("cyan", 6),
                   ("bright_red", 9), ("bright_green", 10), ("bright_yellow", 11), ("bright_blue", 12),
                   ("bright_magenta", 13), ("bright_cyan", 14)):
        alias(key, "color%d" % n)
    alias("magenta", "purple")
    alias("bright_magenta", "bright_purple")
    c.setdefault("light_foreground", c.get("color7", c["foreground"]))
    c.setdefault("bright_foreground", c.get("color15", c["foreground"]))
    c["cursor"] = c["bright_foreground"]
    c.setdefault("lighter_background", c.get("color0", c["background"]))
    c.setdefault("dark_foreground", c.get("color8", c["foreground"]))
    c.setdefault("muted", c.get("color8", c["dark_foreground"]))
    c.setdefault("selection", c.get("selection_background", c.get("color8", c["background"])))
    c.setdefault("selection_background", c["selection"])
    c.setdefault("selection_foreground", c["bright_foreground"])
    c.setdefault("orange", c["yellow"])
    c.setdefault("brown", mix(c["orange"], "#000000", 0.5))
    c.setdefault("dark_background", mix(c["background"], "#000000", 0.25))
    c.setdefault("darker_background", mix(c["background"], "#000000", 0.5))
    for base in ("red", "yellow", "green", "cyan", "blue", "magenta"):
        c.setdefault("bright_" + base, mix(c[base], "#ffffff", 0.2))
    c.setdefault("accent", c["blue"])
    if not c.get("mode"):
        c["mode"] = c.get("theme_type", "")
    if not c["mode"]:
        h = c["background"].lstrip("#")
        c["mode"] = "light" if sum(int(h[i:i + 2], 16) for i in (0, 2, 4)) > 382 else "dark"
    return c


def render(template, c):
    def sub(m):
        key = m.group(1)
        if key.endswith("_strip"):
            return c[key[:-6]].lstrip("#")
        if key.endswith("_rgb"):
            h = c[key[:-4]].lstrip("#")
            return ",".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))
        return c[key]

    return re.sub(r"\{\{\s*([A-Za-z0-9_]+)\s*\}\}", sub, template)


def title(slug):
    return " ".join(w.capitalize() for w in slug.split("-"))


# ── ports ─────────────────────────────────────────────────────────────────────
def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text if text.endswith("\n") else text + "\n")


def port(tid, name, src, c, tpl):
    d = os.path.join(OUT, tid)
    if os.path.isdir(d):
        shutil.rmtree(d)
    os.makedirs(d)
    light = c["mode"] == "light"
    acc, fg, bg, muted, sel = c["accent"], c["foreground"], c["background"], c["muted"], c["selection"]

    shutil.copy(os.path.join(src, "colors.toml"), os.path.join(d, "colors.toml"))
    write(os.path.join(d, "theme.conf"), "name=%s\nmode=%s\n" % (name, c["mode"]))

    # Ghostty: Omarchy's template, included through omac's theme state file
    write(os.path.join(d, "ghostty.conf"), "# Omarchy %s for Ghostty. %s\n%s\nsplit-divider-color = %s\n"
          % (name, HEADER, render(tpl["ghostty.conf.tpl"], c).rstrip("\n"), muted))

    # btop: the theme's own file when it ships one, else Omarchy's template
    own = os.path.join(src, "btop.theme")
    if os.path.isfile(own):
        shutil.copy(own, os.path.join(d, "btop.theme"))
    else:
        write(os.path.join(d, "btop.theme"), "# Omarchy %s for btop. %s\n%s" % (name, HEADER, render(tpl["btop.theme.tpl"], c)))

    # Neovim: the theme's own lazy spec when it ships one, else Omarchy's aether template
    own = os.path.join(src, "neovim.lua")
    if os.path.isfile(own):
        shutil.copy(own, os.path.join(d, "neovim.lua"))
    else:
        write(os.path.join(d, "neovim.lua"), render(tpl["neovim.lua.tpl"], c))

    # VS Code: extension + theme name, shown as a hint
    own = os.path.join(src, "vscode.json")
    if os.path.isfile(own):
        shutil.copy(own, os.path.join(d, "vscode.json"))

    # tmux: Omarchy's tmux status layout with the theme's colors
    write(os.path.join(d, "tmux.conf"), f"""# Omarchy {name} for tmux. {HEADER}
set -g status-style "bg=default,fg={fg}"
set -g status-left "#[fg={bg},bg={acc},bold] #S #[bg=default] "
set -g status-right "#[fg={acc}]#{{?pane_in_mode,COPY ,}}#{{?client_prefix,PREFIX ,}}#{{?window_zoomed_flag,ZOOM ,}}#[fg={muted}]#h "
set -g window-status-format "#[fg={muted}] #I:#W "
set -g window-status-current-format "#[fg={acc},bold] #I:#W "
set -g pane-border-style "fg={muted}"
set -g pane-active-border-style "fg={acc}"
set -g message-style "bg=default,fg={acc}"
set -g message-command-style "bg=default,fg={acc}"
set -g mode-style "bg={sel},fg={c['selection_foreground']}"
setw -g clock-mode-colour "{acc}"
""")

    # lazygit: the block omac swaps into config.yml
    write(os.path.join(d, "lazygit.yml"), f"""# omac-theme-begin (Omarchy {tid}) {HEADER}
gui:
  theme:
    activeBorderColor: ["{acc}", bold]
    inactiveBorderColor: ["{muted}"]
    searchingActiveBorderColor: ["{c['yellow']}", bold]
    optionsTextColor: ["{acc}"]
    selectedLineBgColor: ["{c['lighter_background'] if c['lighter_background'] != bg else sel}"]
    inactiveViewSelectedLineBgColor: ["{c['dark_background']}"]
    cherryPickedCommitFgColor: ["{acc}"]
    cherryPickedCommitBgColor: ["{sel}"]
    markedBaseCommitFgColor: ["{acc}"]
    markedBaseCommitBgColor: ["{sel}"]
    unstagedChangesColor: ["{c['red']}"]
    defaultFgColor: ["{fg}"]
# omac-theme-end
""")

    # fzf
    colors = ",".join([
        "fg:" + fg, "bg:-1", "hl:" + acc, "fg+:" + c["bright_foreground"], "bg+:" + sel, "hl+:" + acc,
        "info:" + muted, "prompt:" + acc, "pointer:" + acc, "marker:" + c["green"], "spinner:" + acc,
        "header:" + muted, "border:" + muted, "gutter:-1",
    ])
    write(os.path.join(d, "fzf.zsh"), f"# Omarchy {name} for fzf. {HEADER}\nexport OMAC_FZF_COLORS='--color={colors}'\n")

    # starship: a palette named "omac" with the color names omac's prompt uses
    write(os.path.join(d, "starship.toml"), f"""# omac-theme-begin (Omarchy {tid}) {HEADER}
[palettes.omac]
accent = "{acc}"
green = "{c['green']}"
orange = "{c['orange']}"
red = "{c['red']}"
muted = "{muted}"
text = "{fg}"
# omac-theme-end
""")

    # herdr CLI: a [theme] table on a built-in base, every color overridden
    write(os.path.join(d, "herdr.toml"), f"""# Omarchy {name} — {HEADER}
# Replaces the [theme] tables of ~/.config/herdr/config.toml (omac theme does this).
[theme]
auto_switch = false
name = "{'one-light' if light else 'one-dark'}"

[theme.custom]
panel_bg = "reset" # let Ghostty's background show through panes
sidebar_bg = "reset"
active_row_bg = "{sel}"
selection_bg = "{sel}"
surface_dim = "{c['dark_background']}"
surface0 = "reset"
surface1 = "{c['lighter_background']}"
overlay0 = "{muted}"
overlay1 = "{c['light_foreground']}"
text = "{fg}"
subtext0 = "{c['dark_foreground']}"
accent = "{acc}"
green = "{c['green']}"
blue = "{c['blue']}"
teal = "{c['cyan']}"
yellow = "{c['yellow']}"
peach = "{c['orange']}"
red = "{c['red']}"
mauve = "{c['magenta']}"
""")

    # herdr app (GUI) theme file
    ansi = [bg, c["red"], c["green"], c["yellow"], c["blue"], c["magenta"], c["cyan"], fg,
            muted, c["bright_red"], c["bright_green"], c["bright_yellow"], c["bright_blue"],
            c["bright_magenta"], c["bright_cyan"], c["bright_foreground"]]
    app = {
        "background": bg, "foreground": fg, "selection": sel, "cursor": c["cursor"], "ansi": ansi,
        "colors": {
            "chrome": bg, "canvas": bg, "surface": bg, "popover": c["dark_background"],
            "raised": c["lighter_background"], "hover": c["dark_background"], "selected": sel,
            "border": muted, "input": muted, "foreground": fg, "muted": c["dark_foreground"],
            "dim": muted, "idle": muted, "unknown": muted, "accent": acc, "accent_foreground": bg,
            "solid": acc, "solid_foreground": bg, "working": acc, "blocked": c["red"], "done": c["green"],
        },
    }
    write(os.path.join(d, "herdr-app.json"), json.dumps(app, indent=2))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("OMARCHY_SRC") or os.path.join(
        ROOT, "..", "research", "device", "omarchy-repo")
    src = os.path.abspath(os.path.expanduser(src))
    themes_dir = os.path.join(src, "themes")
    if not os.path.isdir(themes_dir):
        sys.exit("no themes/ in %s (pass the path to an Omarchy checkout)" % src)
    tpl = {}
    for t in TEMPLATES:
        with open(os.path.join(src, "default", "themed", t)) as f:
            tpl[t] = f.read()

    version = ""
    vf = os.path.join(src, "version")
    if os.path.isfile(vf):
        with open(vf) as f:
            version = f.read().strip()

    rows = []
    for slug in sorted(os.listdir(themes_dir)):
        tdir = os.path.join(themes_dir, slug)
        if not os.path.isfile(os.path.join(tdir, "colors.toml")):
            print("skip", slug, "(no colors.toml)")
            continue
        tid = RENAME.get(slug, slug)
        name = "Omarchy White" if slug == "white" else title(slug)
        c = resolve(parse_colors(os.path.join(tdir, "colors.toml")))
        port(tid, name, tdir, c, tpl)
        rows.append("%s\t%s\t%s" % (tid, c["mode"], name))
        print("wrote omarchy/%s (%s)" % (tid, c["mode"]))

    with open(os.path.join(OUT, "LIST"), "w") as f:
        f.write("# id<TAB>mode<TAB>name. %s Omarchy %s\n" % (HEADER, version))
        f.write("\n".join(rows) + "\n")
    print("%d themes from Omarchy %s" % (len(rows), version or "?"))
    raycast_dropdown(rows)
    gallery(rows)


def ghostty_colors(path):
    """background, foreground and the 16 palette slots from a Ghostty theme file."""
    out = {"palette": {}}
    with open(path) as f:
        for line in f:
            m = re.match(r"\s*palette\s*=\s*(\d+)\s*=\s*(#?[0-9A-Fa-f]{6})", line)
            if m:
                out["palette"][int(m.group(1))] = "#" + m.group(2).lstrip("#")
                continue
            m = re.match(r"\s*(background|foreground)\s*=\s*(#?[0-9A-Fa-f]{6})", line)
            if m:
                out[m.group(1)] = "#" + m.group(2).lstrip("#")
    return out


def gallery(rows):
    """docs/themes.svg: one card per theme, drawn from its real terminal colors."""
    bb = os.path.join(ROOT, "baby-blue", "ghostty", "themes")
    cards = [("Baby Blue White", "white", ghostty_colors(os.path.join(bb, "Baby Blue White")), "#1677a8"),
             ("Baby Blue Dark", "dark", ghostty_colors(os.path.join(bb, "Baby Blue")), "#89CFF0")]
    for r in rows:
        tid, _, name = r.split("\t")
        c = resolve(parse_colors(os.path.join(OUT, tid, "colors.toml")))
        cards.append((name, tid, ghostty_colors(os.path.join(OUT, tid, "ghostty.conf")), c["accent"]))

    cols, w, h, gap = 5, 240, 112, 14
    nrows = (len(cards) + cols - 1) // cols
    W, H = cols * w + (cols + 1) * gap, nrows * h + (nrows + 1) * gap
    font = "ui-monospace,SFMono-Regular,Menlo,Consolas,monospace"
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" font-family="%s">'
           % (W, H, W, H, font)]
    for i, (name, tid, g, acc) in enumerate(cards):
        x, y = gap + (i % cols) * (w + gap), gap + (i // cols) * (h + gap)
        bg, fg = g["background"], g["foreground"]
        out.append('<g transform="translate(%d,%d)">' % (x, y))
        out.append('<rect width="%d" height="%d" rx="10" fill="%s" stroke="#8888884d"/>' % (w, h, bg))
        for k, dot in enumerate(("#ff5f57", "#febc2e", "#28c840")):
            out.append('<circle cx="%d" cy="14" r="4.5" fill="%s"/>' % (16 + k * 14, dot))
        out.append('<text x="16" y="44" fill="%s" font-size="15" font-weight="700">%s</text>' % (fg, name))
        out.append('<text x="16" y="66" font-size="11.5"><tspan fill="%s">❯</tspan>'
                   '<tspan fill="%s" dx="6">omac theme </tspan><tspan fill="%s">%s</tspan></text>'
                   % (acc, fg, acc, tid))
        for k, slot in enumerate((1, 2, 3, 4, 5, 6)):
            out.append('<rect x="%d" y="82" width="26" height="14" rx="3" fill="%s"/>'
                       % (16 + k * 32, g["palette"].get(slot, fg)))
        out.append('<rect x="%d" y="82" width="14" height="14" rx="3" fill="%s"/>' % (w - 30, acc))
        out.append("</g>")
    out.append("</svg>")
    path = os.path.join(ROOT, "..", "docs", "themes.svg")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote docs/themes.svg (%d themes)" % len(cards))


def raycast_dropdown(rows):
    """Raycast reads the dropdown from the script header, so list every theme there."""
    path = os.path.join(ROOT, "..", "raycast", "omac-theme.sh")
    data = [{"title": "Baby Blue White", "value": "white"}, {"title": "Baby Blue Dark", "value": "dark"}]
    data += [{"title": r.split("\t")[2], "value": r.split("\t")[0]} for r in rows]
    arg = {"type": "dropdown", "placeholder": "theme", "data": data}
    with open(path) as f:
        text = f.read()
    text = re.sub(r"^# @raycast\.argument1 .*$", "# @raycast.argument1 " + json.dumps(arg, ensure_ascii=False),
                  text, count=1, flags=re.M)
    with open(path, "w") as f:
        f.write(text)
    print("updated raycast/omac-theme.sh")


if __name__ == "__main__":
    main()
