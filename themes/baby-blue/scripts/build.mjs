// Builds every non-VS Code port from palette.json.
// Usage: node scripts/build.mjs        (then ./install.sh to copy into ~/.config)
//
// Outputs (dark + white each):
//   ghostty/themes/Baby Blue{, White}
//   btop/themes/baby-blue{,-white}.theme
//   herdr-app/themes/baby-blue{,-white}.json      (herdr desktop app)
//   herdr/baby-blue{,-dark,-auto}.toml            (herdr CLI: [theme] block; white, dark, follow terminal)
//   starship/palettes.toml
//   nvim/lua/baby-blue/palette.lua

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const palette = JSON.parse(readFileSync(join(root, "palette.json"), "utf8"));

const VARIANTS = [
  { key: "dark", title: "Baby Blue", slug: "baby-blue", p: palette.dark },
  { key: "white", title: "Baby Blue White", slug: "baby-blue-white", p: palette.white },
];

const HEADER = "Generated by scripts/build.mjs from palette.json. Edit the palette, not this file.";

function write(rel, text) {
  const path = join(root, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text.endsWith("\n") ? text : text + "\n");
  console.log("wrote", rel);
}

const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const hex = (c) => "#" + c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
/** a over b: t = how much of a */
const mix = (a, b, t) => hex(rgb(a).map((v, i) => v * t + rgb(b)[i] * (1 - t)));
const solid = (h) => h.slice(0, 7);

// Colors every port shares, derived once.
function derive(p) {
  const dark = rgb(p.bg)[0] < 128;
  return {
    ...p,
    accent: solid(p.accent),
    dim: dark ? "#808080" : "#8a8a8a", // inactive text
    onFill: "#181818", // text on a baby blue / orange fill
    onAccent: dark ? "#181818" : "#ffffff", // text on the accent color itself
    cursorLine: mix(p.pink, p.bg, dark ? 0.1 : 0.12),
    diffAdd: mix(p.string, p.bg, dark ? 0.16 : 0.14),
    diffDelete: mix(p.error, p.bg, dark ? 0.16 : 0.12),
    diffChange: mix(p.accentFill, p.bg, dark ? 0.12 : 0.18),
    diffText: mix(p.accentFill, p.bg, dark ? 0.26 : 0.36),
    search: mix(p.comment, p.bg, dark ? 0.3 : 0.25),
    dimOf: (c) => mix(c, p.bg, 0.55),
  };
}

const herdrTui = {};

for (const { key, title, slug, p: raw } of VARIANTS) {
  const c = derive(raw);
  const t = c.terminal;

  // ── Ghostty ───────────────────────────────────────────────
  write(`ghostty/themes/${title}`, [
    `# ${title} — ${HEADER}`,
    ...t.map((col, i) => `palette = ${i}=${col}`),
    `background = ${c.bg}`,
    `foreground = ${c.fg}`,
    `cursor-color = ${c.accent}`,
    `cursor-text = ${c.bg}`,
    `selection-background = ${c.selectionSolid}`,
    `selection-foreground = ${c.fg}`,
    `split-divider-color = ${c.guide}`,
  ].join("\n"));

  // ── btop ──────────────────────────────────────────────────
  const b = {
    main_bg: c.bg, main_fg: c.fg, title: c.fg, hi_fg: c.accent,
    selected_bg: c.selectionSolid, selected_fg: c.fg, inactive_fg: c.dim,
    graph_text: c.muted, meter_bg: c.surfaceHi, proc_misc: c.accent,
    cpu_box: c.lineNumber, mem_box: c.lineNumber, net_box: c.lineNumber, proc_box: c.lineNumber,
    div_line: c.guide,
    temp_start: c.accent, temp_mid: c.comment, temp_end: c.error,
    cpu_start: c.accent, cpu_mid: c.pink, cpu_end: c.error,
    free_start: c.dimOf(c.string), free_mid: c.string, free_end: c.string,
    cached_start: c.dimOf(c.accent), cached_mid: c.accent, cached_end: c.accent,
    available_start: c.dimOf(c.string), available_mid: c.string, available_end: c.string,
    used_start: c.comment, used_mid: c.comment, used_end: c.error,
    download_start: c.dimOf(c.accent), download_mid: c.accent, download_end: c.accent,
    upload_start: c.dimOf(c.pink), upload_mid: c.pink, upload_end: c.pink,
    process_start: c.accent, process_mid: c.pink, process_end: c.error,
  };
  write(`btop/themes/${slug}.theme`,
    `# ${title} — ${HEADER}\n` + Object.entries(b).map(([k, v]) => `theme[${k}]="${v}"`).join("\n"));

  // ── herdr desktop app ─────────────────────────────────────
  write(`herdr-app/themes/${slug}.json`, JSON.stringify({
    background: c.bg, foreground: c.fg, selection: c.selectionSolid, cursor: c.accent,
    ansi: t,
    colors: {
      chrome: c.bg, canvas: c.bg, surface: c.bg, popover: c.surface, raised: c.surfaceHi,
      hover: c.surface, selected: c.selectionSolid, border: c.guide, input: c.lineNumber,
      foreground: c.fg, muted: c.muted, dim: c.dim, idle: c.dim, unknown: c.dim,
      accent: c.accent, accent_foreground: c.onAccent,
      solid: c.accentFill, solid_foreground: c.onFill,
      working: c.accent, blocked: c.error, done: c.string,
    },
  }, null, 2));

  // ── herdr terminal app (collected; written below) ─────────
  const h = {
    // sidebar + inactive tabs are transparent so Ghostty's glass background shows through,
    // so the dim text greys are one step darker than usual to stay readable on it.
    sidebar_bg: "reset", active_row_bg: c.selectionSolid, selection_bg: c.selectionSolid,
    surface_dim: c.surface, surface0: "reset", surface1: c.surfaceHi,
    overlay0: c.dim, overlay1: mix(c.dim, c.fg, 0.6), text: c.fg, subtext0: c.muted,
    accent: c.accentFill, // active tab fill: baby blue in both variants
    green: c.string, blue: t[12], teal: t[6],
    yellow: c.accent, // no yellow
    peach: c.comment, red: c.error, mauve: c.pink,
  };
  herdrTui[key] = h;

  VARIANTS.find((v) => v.key === key).c = c;
}

// ── herdr terminal app (CLI): fixed white (default), fixed dark, or follow the terminal ──
const kv = (o) => Object.entries(o).map(([k, v]) => `${k} = "${v}"`).join("\n");
const herdrHead = (what) => [
  `# Baby Blue ${what} — ${HEADER}`,
  `# Replaces the [theme] section of ~/.config/herdr/config.toml (install.sh does this).`,
];
const herdrFixed = (base, colors) => [
  `[theme]`,
  `auto_switch = false`,
  `name = "${base}"`,
  ``,
  `[theme.custom]`,
  `panel_bg = "reset" # let Ghostty's background show through panes`,
  kv(colors),
].join("\n");
write("herdr/baby-blue.toml", [...herdrHead("White (default)"), herdrFixed("one-light", herdrTui.white)].join("\n"));
write("herdr/baby-blue-dark.toml", [...herdrHead("Dark"), herdrFixed("vesper", herdrTui.dark)].join("\n"));
write("herdr/baby-blue-auto.toml", [
  ...herdrHead("(follows the terminal's light/dark)"),
  `[theme]`,
  `auto_switch = true`,
  `dark_name = "vesper"`,
  `light_name = "one-light"`,
  ``,
  `[theme.custom]`,
  `panel_bg = "reset" # let Ghostty's background show through panes`,
  ``,
  `[theme.custom.dark]`,
  kv(herdrTui.dark),
  ``,
  `[theme.custom.light]`,
  kv(herdrTui.white),
].join("\n"));

// ── Starship ──────────────────────────────────────────────
write("starship/palettes.toml", [
  `# ${HEADER}`,
  `# Pick one in starship.toml: palette = "baby_blue_white" (default)  or  palette = "baby_blue" (dark)`,
  ...VARIANTS.map(({ key, c }) => [
    ``,
    `[palettes.${key === "dark" ? "baby_blue" : "baby_blue_white"}]`,
    `accent = "${c.accentFill}"`, // the real baby blue, also on white (accent there is a darker text blue)
    `green = "${c.string}"`,
    `orange = "${c.comment}"`,
    `red = "${c.error}"`,
    `muted = "${c.muted}"`,
    `text = "${c.fg}"`,
  ].join("\n")),
].join("\n"));

// ── Neovim palette ────────────────────────────────────────
const NVIM_KEYS = ["bg", "fg", "muted", "accent", "accentFill", "string", "comment", "link", "frame",
  "lineNumber", "guide", "error", "invalid", "surface", "surfaceHi", "pink", "selectionSolid",
  "dim", "onFill", "onAccent", "cursorLine", "diffAdd", "diffDelete", "diffChange", "diffText", "search"];
const lua = (c) => [
  ...NVIM_KEYS.map((k) => `    ${k} = "${c[k]}",`),
  `    terminal = { ${c.terminal.map((x) => `"${x}"`).join(", ")} },`,
].join("\n");
write("nvim/lua/baby-blue/palette.lua", [
  `-- ${HEADER}`,
  `return {`,
  ...VARIANTS.map(({ key, c }) => `  ${key} = {\n${lua(c)}\n  },`),
  `}`,
].join("\n"));
