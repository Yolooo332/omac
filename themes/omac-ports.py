#!/usr/bin/env python3
"""Generate the Baby Blue ports omac adds on top of themes/baby-blue:
tmux, lazygit, fzf. Reads themes/baby-blue/palette.json.

Usage: python3 -I themes/omac-ports.py   (outputs are committed; re-run after editing the palette)
"""
import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
BB = os.path.join(ROOT, "baby-blue")
HEADER = "Generated by themes/omac-ports.py from baby-blue/palette.json. Edit the palette, not this file."


def solid(h):
    return h[:7]


def write(rel, text):
    path = os.path.join(BB, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text if text.endswith("\n") else text + "\n")
    print("wrote", os.path.relpath(path, ROOT))


def ports(key, p):
    dark = key == "dark"
    dim = "#808080" if dark else "#8a8a8a"
    on_fill = "#181818"
    accent = solid(p["accent"])
    fill = solid(p["accentFill"])

    # tmux: same layout as Omarchy's tmux theme, baby blue colors
    write(f"tmux/{key}.conf", f"""# Baby Blue {key} for tmux. {HEADER}
set -g status-style "bg=default,fg={p['fg']}"
set -g status-left "#[fg={on_fill},bg={fill},bold] #S #[bg=default] "
set -g status-right "#[fg={accent}]#{{?pane_in_mode,COPY ,}}#{{?client_prefix,PREFIX ,}}#{{?window_zoomed_flag,ZOOM ,}}#[fg={dim}]#h "
set -g window-status-format "#[fg={dim}] #I:#W "
set -g window-status-current-format "#[fg={accent},bold] #I:#W "
set -g pane-border-style "fg={p['guide']}"
set -g pane-active-border-style "fg={accent}"
set -g message-style "bg=default,fg={accent}"
set -g message-command-style "bg=default,fg={accent}"
set -g mode-style "bg={p['selectionSolid']},fg={p['fg']}"
setw -g clock-mode-colour "{accent}"
""")

    # lazygit: a block omac swaps into config.yml
    write(f"lazygit/{key}.yml", f"""# omac-theme-begin (Baby Blue {key}) {HEADER}
gui:
  theme:
    activeBorderColor: ["{accent}", bold]
    inactiveBorderColor: ["{p['lineNumber'] if dark else '#c2c2c2'}"]
    searchingActiveBorderColor: ["{p['comment']}", bold]
    optionsTextColor: ["{accent}"]
    selectedLineBgColor: ["{p['surfaceHi']}"]
    inactiveViewSelectedLineBgColor: ["{p['surface']}"]
    cherryPickedCommitFgColor: ["{accent}"]
    cherryPickedCommitBgColor: ["{p['selectionSolid']}"]
    markedBaseCommitFgColor: ["{accent}"]
    markedBaseCommitBgColor: ["{p['selectionSolid']}"]
    unstagedChangesColor: ["{p['error']}"]
    defaultFgColor: ["{p['fg']}"]
# omac-theme-end
""")

    # fzf colors (sourced by the zsh theme file)
    colors = ",".join([
        "fg:" + p["fg"], "bg:-1", "hl:" + accent,
        "fg+:" + p["fg"], "bg+:" + p["surfaceHi"], "hl+:" + accent,
        "info:" + p["muted"], "prompt:" + accent, "pointer:" + accent,
        "marker:" + p["string"], "spinner:" + accent, "header:" + p["muted"],
        "border:" + (p["guide"] if dark else "#d0d0d0"), "gutter:-1",
    ])
    write(f"fzf/{key}.zsh", f"""# Baby Blue {key} for fzf. {HEADER}
export OMAC_FZF_COLORS='--color={colors}'
""")


def main():
    with open(os.path.join(BB, "palette.json")) as f:
        palette = json.load(f)
    for key in ("white", "dark"):
        ports(key, palette[key])


if __name__ == "__main__":
    main()
